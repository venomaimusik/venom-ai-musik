const playlist = document.getElementById("playlist");
const audio = document.getElementById("audio");
const cover = document.getElementById("cover");
const title = document.getElementById("title");
const progress = document.getElementById("progress");
const currentTime = document.getElementById("currentTime");
const duration = document.getElementById("duration");
const volume = document.getElementById("volume");

const playBtn = document.getElementById("playBtn");
const prevBtn = document.getElementById("prevBtn");
const nextBtn = document.getElementById("nextBtn");
const shuffleBtn = document.getElementById("shuffleBtn");
const favoriteBtn = document.getElementById("favoriteBtn");
let currentSong = 0;
let favorites = JSON.parse(localStorage.getItem("favorites")) || [];

function loadSong(index) {
    const song = songs[index];

    audio.src = song.file;
    cover.src = song.cover;
    title.textContent = song.title;
    favoriteBtn.textContent = favorites.includes(song.title) ? "❤️" : "🤍";
    progress.style.width = "0%";
    
}
audio.addEventListener("loadedmetadata", () => {
    duration.textContent = formatTime(audio.duration);
});

playBtn.addEventListener("click", () => {
    if (audio.src) {
        audio.play();
    }
});

prevBtn.addEventListener("click", () => {
    currentSong--;
    if (currentSong < 0) currentSong = songs.length - 1;

    loadSong(currentSong);
    audio.play();
});

nextBtn.addEventListener("click", () => {
    currentSong++;
    if (currentSong >= songs.length) currentSong = 0;

    loadSong(currentSong);
    audio.play();
});

loadSong(0);

songs.forEach(song => {

    const button = document.createElement("button");

    button.className = "song-btn";

    button.textContent = "🎵 " + song.title;

    button.onclick = () => {

        audio.src = song.file;
cover.src = song.cover;
title.textContent = song.title;

audio.load();
audio.play();
currentSong = songs.indexOf(song);
    };

    playlist.appendChild(button);

});
audio.addEventListener("timeupdate", () => {

    const percent = audio.duration ? (audio.currentTime / audio.duration) * 100 : 0;

    currentTime.textContent = formatTime(audio.currentTime);
    duration.textContent = formatTime(audio.duration);

});

volume.addEventListener("input", () => {
    audio.volume = volume.value;
});

function formatTime(seconds) {

    if (isNaN(seconds)) return "0:00";

    const min = Math.floor(seconds / 60);
    const sec = Math.floor(seconds % 60);

    return `${min}:${sec.toString().padStart(2,"0")}`;
}
audio.addEventListener("loadedmetadata", () => {
    duration.textContent = formatTime(audio.duration);
});

audio.addEventListener("timeupdate", () => {
    if (audio.duration) {
        progress.style.width =
            (audio.currentTime / audio.duration) * 100 + "%";
    }
});
const search = document.getElementById("searchInput");

search.addEventListener("input", () => {
    const text = search.value.toLowerCase();

    document.querySelectorAll(".song-btn").forEach(button => {
        if (button.textContent.toLowerCase().includes(text)) {
            button.style.display = "";
        } else {
            button.style.display = "none";
        }
    });
});
let shuffle = false;

shuffleBtn.addEventListener("click", () => {
    shuffle = !shuffle;
    shuffleBtn.style.color = shuffle ? "#00ff99" : "";
});
audio.addEventListener("ended", () => {

    if (shuffle) {
        currentSong = Math.floor(Math.random() * songs.length);
    } else {
        currentSong++;

        if (currentSong >= songs.length) {
            currentSong = 0;
        }
    }

    loadSong(currentSong);
    audio.play();
});

favoriteBtn.addEventListener("click", () => {
    const song = songs[currentSong];

    if (favorites.includes(song.title)) {
        favorites = favorites.filter(title => title !== song.title);
        favoriteBtn.textContent = "🤍";
    } else {
        favorites.push(song.title);
        favoriteBtn.textContent = "❤️";
    }

    localStorage.setItem("favorites", JSON.stringify(favorites));
});